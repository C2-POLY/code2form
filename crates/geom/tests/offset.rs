//! `offset(r = ...)` against the reference implementation (2021.01).
//!
//! The expected points were measured on the macOS build of the reference
//! release (2021.01): each snippet was exported with its `-o out.svg`
//! and the points read from the SVG path (y negated back). The SVG prints
//! six significant digits, hence the tolerances. The letter is the outline
//! of Liberation Sans "G" at size 10 as the reference draws it, given as
//! a polygon so that this test needs no font.

use std::path::Path;

use c2f_geom::Model;

fn points(src: &str) -> Vec<Vec<[f64; 2]>> {
    let program = c2f_eval::Program::load(src, Path::new("offset.scad"), &[]).unwrap_or_else(|_| panic!("{src} loads"));
    let output = c2f_eval::evaluate(&program);
    let rendered = c2f_geom::render(&output.nodes);
    assert!(rendered.warnings.is_empty(), "{src}: {:?}", rendered.warnings);
    let Model::Flat(section) = rendered.model else { panic!("{src} is not 2D") };
    section.to_polygons().iter().map(|c| c.iter().map(|p| [p.x, p.y]).collect()).collect()
}

/// Contours separated by blank lines, of `x,y` points.
fn parse(expected: &str) -> Vec<Vec<[f64; 2]>> {
    let mut contours = vec![Vec::new()];
    for line in expected.lines() {
        if line.trim().is_empty() {
            if !contours.last().unwrap().is_empty() {
                contours.push(Vec::new());
            }
            continue;
        }
        for pair in line.split_whitespace() {
            let number = |s: &str| s.parse::<f64>().unwrap_or_else(|_| panic!("bad point {pair}"));
            let (x, y) = pair.split_once(',').unwrap_or_else(|| panic!("bad point {pair}"));
            contours.last_mut().unwrap().push([number(x), number(y)]);
        }
    }
    contours.retain(|c| !c.is_empty());
    contours
}

/// Within half a unit of the sixth significant digit that the SVG export
/// prints (plus the cross-section's 1e-8 precision).
fn close(actual: f64, expected: f64) -> bool {
    let half_digit = if expected == 0.0 { 0.0 } else { 0.5 * 10f64.powf(expected.abs().log10().floor() - 5.0) };
    (actual - expected).abs() <= half_digit * (1.0 + 1e-9) + 2e-8
}

fn area(contours: &[Vec<[f64; 2]>]) -> f64 {
    contours
        .iter()
        .flat_map(|c| (0..c.len()).map(|i| (c[i], c[(i + 1) % c.len()])))
        .map(|(a, b)| (a[0] * b[1] - b[0] * a[1]) / 2.0)
        .sum()
}

/// Every contour has the reference's points, in any order and starting
/// anywhere, and the same area.
fn check(src: &str, expected: &str) {
    let ours = points(src);
    let reference = parse(expected);
    let mut counts: Vec<usize> = ours.iter().map(Vec::len).collect();
    let mut want: Vec<usize> = reference.iter().map(Vec::len).collect();
    counts.sort_unstable();
    want.sort_unstable();
    assert_eq!(counts, want, "{src}: points per contour");
    let matches = |p: &[f64; 2], q: &[f64; 2]| close(p[0], q[0]) && close(p[1], q[1]);
    let ours_flat: Vec<[f64; 2]> = ours.iter().flatten().copied().collect();
    for q in reference.iter().flatten() {
        assert!(ours_flat.iter().any(|p| matches(p, q)), "{src}: no point at {q:?}");
    }
    for p in &ours_flat {
        assert!(reference.iter().flatten().any(|q| matches(p, q)), "{src}: {p:?} is not the reference's");
    }
    // The reference's area comes from its rounded points.
    let (got, want) = (area(&ours), area(&reference));
    assert!((got - want).abs() <= 1e-6 * want.abs(), "{src}: area {got} vs {want}");
}

