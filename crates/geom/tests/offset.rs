#[test]
fn concave_outline() {
    // 7 segments a turn for r = 2: the right angles get round(7 / 4) = 2
    // segments, one step of 360 / 7 degrees and a shorter one, the top
    // corners (140 degrees) 3, and the notch's offsets cross at
    // (10, 11.1241).
    check(
        "offset(r=2) polygon([[0,0],[20,0],[20,20],[10,8],[0,20]]);",
        "
        21.5637,-1.24698 22,0 22,20 21.247,21.5637 19.555,21.9499 18.4636,21.2804 10,11.1241
        1.53644,21.2804 -0.0430756,21.9995 -1.59016,21.213 -2,20 -2,0 -1.24698,-1.56366 0,-2 20,-2
        ",
    );
}

