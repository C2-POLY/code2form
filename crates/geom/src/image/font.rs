/// What a character missing from the font draws: a box.
const MISSING: [u8; HEIGHT] = [0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111];

fn glyph(c: char) -> [u8; HEIGHT] {
    GLYPHS.iter().find(|(g, _)| *g == c).map_or(MISSING, |(_, rows)| *rows)
}

/// How wide `text` is drawn, each font pixel a square of `size` pixels.
pub fn width(text: &str, size: usize) -> usize {
    (text.chars().count() * ADVANCE).saturating_sub(1) * size
}

/// Draws `text` into `rgb`, an image `width` pixels wide, its top left
/// corner at `x`, `y`, each font pixel a square of `size` pixels; what
/// falls outside the image is left out.
pub fn draw(rgb: &mut [u8], width: usize, [x, y]: [usize; 2], text: &str, size: usize, color: [u8; 3]) {
    let height = rgb.len() / 3 / width.max(1);
    for (n, c) in text.chars().enumerate() {
        let left = x + n * ADVANCE * size;
        for (row, bits) in glyph(c).into_iter().enumerate() {
            for column in (0..WIDTH).filter(|column| bits & (1 << (WIDTH - 1 - column)) != 0) {
                for k in 0..size * size {
                    let (px, py) = (left + column * size + k % size, y + row * size + k / size);
                    if px < width && py < height {
                        rgb[(py * width + px) * 3..][..3].copy_from_slice(&color);
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn one_glyph_per_character_within_its_cell() {
        for (c, rows) in GLYPHS {
            assert!(rows.iter().all(|row| *row < 1 << WIDTH), "{c:?}");
        }
        let mut chars: Vec<char> = GLYPHS.iter().map(|(c, _)| *c).collect();
        chars.sort();
        chars.dedup();
        assert_eq!(chars.len(), GLYPHS.len());
    }

    #[test]
    fn draws_at_its_size() {
        // A 1 at size 2: its foot is a bar three font pixels wide.
        let mut rgb = vec![0; 20 * 20 * 3];
        draw(&mut rgb, 20, [1, 1], "1", 2, [255, 255, 255]);
        let lit = |x: usize, y: usize| rgb[(y * 20 + x) * 3] == 255;
        assert!((3..9).all(|x| lit(x, 13) && lit(x, 14)));
        assert!(!lit(1, 13) && !lit(9, 13));
        assert_eq!((width("1", 2), width("12", 1), width("", 3)), (10, 11, 0));
        // Off the image's edge: left out, not a panic.
        draw(&mut rgb, 20, [18, 18], "×", 3, [255, 255, 255]);
    }
}
